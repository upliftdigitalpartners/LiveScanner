# The helicopter is not a winged aircraft and must not read as one. A fat pod on
# a thin boom gives it a different silhouette, and the rotor blades sit at 45
# degrees so they cannot be mistaken for wings — blades drawn along the axes
# merge with the fuselage and the whole thing turns into a plus sign.
ROTORCRAFT = {
    "comment": "A7 rotorcraft — pod, thin tail boom, and a rotor disc set off-axis.",
    "body": [
        (50, 24), (59, 31), (60, 43),
        (55, 50),
        (52, 54),
        (52, 78),
        (64, 83), (64, 91), (52, 91),
        (51, 95),
    ],
    "rotor_radius": 46.0,
    "blade_half_width": 2.6,
    "blade_angles_deg": (45.0, 135.0),
    "hub": (50.0, 50.0, 6.0),
}

def mirrored(outline: list[tuple[float, float]]) -> str:
    """One closed path: the given right half, then its mirror up the left side."""
    points = [f"M{outline[0][0]},{outline[0][1]}"]
    for x, y in outline[1:]:
        points.append(f"L{x},{y}")
    # Back up the left side, skipping the last point so the tail tip isn't doubled.
    for x, y in reversed(outline[:-1]):
        points.append(f"L{100 - x},{y}")
    points.append("Z")
    return " ".join(points)


def vector_xml(comment: str, paths: list[str]) -> str:
    body = "\n".join(
        f'    <path\n        android:fillColor="#FFFFFFFF"\n        android:pathData="{d}" />'
        for d in paths
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by tools/build_aircraft_icons.py — edit that, not this.
     Nose points to 12 o'clock; the scope rotates it by the aircraft's track.
     Fill is plain white so android:tint can colour it from the altitude ramp. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="100"
    android:viewportHeight="100"
    android:tint="#FFFFFFFF">
{body}
</vector>
"""


def rotorcraft_paths() -> list[str]:
    """The pod and boom, plus two blades through the hub at 45 and 135 degrees."""
    import math

    cx, cy, hub_r = ROTORCRAFT["hub"]
    radius = ROTORCRAFT["rotor_radius"]
    half = ROTORCRAFT["blade_half_width"]

    paths = [mirrored(ROTORCRAFT["body"])]
    for degrees in ROTORCRAFT["blade_angles_deg"]:
        theta = math.radians(degrees)
        dx, dy = math.cos(theta), math.sin(theta)
        # Perpendicular, to give the blade its width.
        px, py = -dy, dx
        corners = [
            (cx + dx * radius + px * half, cy + dy * radius + py * half),
            (cx + dx * radius - px * half, cy + dy * radius - py * half),
            (cx - dx * radius - px * half, cy - dy * radius - py * half),
            (cx - dx * radius + px * half, cy - dy * radius + py * half),
        ]
        d = " ".join(
            f"{'M' if i == 0 else 'L'}{x:.1f},{y:.1f}" for i, (x, y) in enumerate(corners)
        )
        paths.append(d + " Z")

    paths.append(
        f"M{cx - hub_r},{cy} a{hub_r},{hub_r} 0 1,0 {2 * hub_r},0 "
        f"a{hub_r},{hub_r} 0 1,0 {-2 * hub_r},0 Z"
    )
    return paths


