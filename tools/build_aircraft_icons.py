#!/usr/bin/env python3
"""Build the radar scope's aircraft silhouettes as Android VectorDrawables.

Targets on the scope are all the same diamond today. Colour already carries
altitude, so shape is free to carry what kind of aircraft it is — which is
information rather than decoration.

These are generated rather than drawn by hand or by an image model because the
requirements are geometric, and a generator can guarantee what matters:

  * perfect bilateral symmetry — only the right half is written out below, and
    the left is its mirror, so the two can never drift apart
  * nose at exactly 12 o'clock — the scope rotates each icon by the aircraft's
    track, and any other baseline puts every target on screen at a wrong angle
  * a single flat fill with no colour of its own, so android:tint can set it
    from the altitude ramp at draw time

Run --preview to rasterise each shape to the terminal. There is no way to open
a PNG in a build pipeline, and a silhouette that is secretly a blob is worth
catching before it ships.

Usage:
    python3 tools/build_aircraft_icons.py
    python3 tools/build_aircraft_icons.py --preview
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "app/src/main/res/drawable"

# Everything is described in a 100x100 box: x=50 is the centreline, y=0 is the
# nose end. Each entry lists the RIGHT half only, nose first, running aft.
