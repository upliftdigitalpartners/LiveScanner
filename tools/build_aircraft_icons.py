def rasterise(paths: list[str], cols: int = 60, rows: int = 30) -> str:
    """Crude fill of the generated paths, so a wrong shape is visible here."""
    polys, rects, circles = [], [], []
    for d in paths:
        if " a" in d:  # the hub arc; approximate it as a circle
            cx, cy, r = ROTORCRAFT["hub"]
            circles.append((cx, cy, r))
            continue
        pts = []
        for token in d.replace("Z", "").split():
            if token[0] in "ML":
                x, y = token[1:].split(",")
                pts.append((float(x), float(y)))
        if len(pts) == 4:
            rects.append(pts)
        polys.append(pts)

    def inside(px: float, py: float, poly: list[tuple[float, float]]) -> bool:
        hit = False
        n = len(poly)
        for i in range(n):
            x1, y1 = poly[i]
            x2, y2 = poly[(i + 1) % n]
            if (y1 > py) != (y2 > py):
                xx = (x2 - x1) * (py - y1) / (y2 - y1) + x1
                if px < xx:
                    hit = not hit
        return hit

    lines = []
    for r in range(rows):
        py = (r + 0.5) * 100.0 / rows
        line = []
        for c in range(cols):
            px = (c + 0.5) * 100.0 / cols
            on = any(inside(px, py, poly) for poly in polys)
            on = on or any((px - cx) ** 2 + (py - cy) ** 2 <= rr * rr for cx, cy, rr in circles)
            line.append("##" [0] if on else " ")
        lines.append("".join(line))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--preview", action="store_true", help="rasterise to the terminal")
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    args = parser.parse_args()

    built: dict[str, list[str]] = {
        name: [mirrored(spec["outline"])] for name, spec in SHAPES.items()
    }
    built["ic_ac_rotorcraft"] = rotorcraft_paths()
    comments = {name: spec["comment"] for name, spec in SHAPES.items()}
    comments["ic_ac_rotorcraft"] = ROTORCRAFT["comment"]

    if args.preview:
        for name, paths in built.items():
            print(f"\n=== {name} — {comments[name]}")
            print(rasterise(paths))
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
    for name, paths in built.items():
        path = args.out / f"{name}.xml"
        path.write_text(vector_xml(comments[name], paths))
        print(f"  {path.relative_to(ROOT)}  ({path.stat().st_size} bytes)")
    print(f"\n{len(built)} silhouettes written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
